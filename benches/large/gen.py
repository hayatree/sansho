#!/usr/bin/env python3
"""Generate standalone transistor-level arithmetic, inverter and grid decks.

Provenance: original circuits derived from unsigned binary arithmetic and static
CMOS truth tables. The generic BSIM4 cards come from this project's inverter.
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
VECTORS = [(0, 0), (0xDB69, 0x9DB7), (0x6DB6, 0xE6D9), (0xFFFF, 0xFFFF)]
VECTOR_NS = {"mos1": 2, "bsim4": 8}


def header(title, model=None):
    lines = [f"* {title}", "* Provenance: original circuit generated by benches/large/gen.py."]
    if model == "bsim4":
        source = (HERE.parents[1] / "verify/bsim4-decks/b4_inverter_tran.cir").read_text()
        lines.extend(s for s in source.splitlines() if s.startswith((".model", "+")))
    elif model == "mos1":
        lines += [".model n1 nmos(level=1 vto=0.43 kp=190u lambda=0.025)",
                  ".model p1 pmos(level=1 vto=-0.45 kp=86u lambda=0.028)"]
    return lines


def gate(name, ports, transistors):
    lines = [f".subckt {name} {ports} y vdd"]
    for i, (kind, drain, control, source) in enumerate(transistors):
        bulk, width = ("0", 1) if kind == "n" else ("vdd", 2)
        lines.append(f"m{i} {drain} {control} {source} {bulk} {kind}1 w={width}u l=0.12u")
    if name != "inv":
        lines += ["cm mid 0 1f", "rleak mid 0 20meg"]
    return lines + ["cl y 0 3f", ".ends"]


INV = gate("inv", "a", [("p", "y", "a", "vdd"), ("n", "y", "a", "0")])
NAND = gate("nand2", "a b", [("p", "y", "a", "vdd"), ("p", "y", "b", "vdd"),
                              ("n", "y", "a", "mid"), ("n", "mid", "b", "0")])
NOR = gate("nor2", "a b", [("n", "y", "a", "0"), ("n", "y", "b", "0"),
                            ("p", "y", "a", "mid"), ("p", "mid", "b", "vdd")])


def multiplier(model):
    period = VECTOR_NS[model]
    lines = header("16 by 16 unsigned carry-save multiplier", model) + INV + NAND + NOR
    lines += ["vdd vdd 0 1.8"]
    for operand, prefix in enumerate("ab"):
        for bit in range(16):
            levels = ["1.8" if (v[operand] >> bit) & 1 else "0" for v in VECTORS]
            points = ["0", levels[0]]
            for i, (old, new) in enumerate(zip(levels, levels[1:]), 1):
                if old != new:
                    points.extend([f"{i * period}n", old, f"{i * period * 1000 + 40}p", new])
            wave = f"pwl({' '.join(points)})" if len(points) > 2 else levels[0]
            lines.append(f"v{prefix}{bit} {prefix}{bit} 0 {wave}")

    gate_id = 0

    def cell(kind, *inputs, out=None):
        nonlocal gate_id
        gate_id += 1
        out = out or f"w{gate_id}"
        lines.append(f"x{gate_id} {' '.join(inputs)} {out} vdd {kind}")
        return out

    def xor(a, b):
        ab = cell("nand2", a, b)
        return cell("nand2", cell("nand2", a, ab), cell("nand2", b, ab)), ab

    def add(bits):
        if len(bits) == 1:
            return bits[0], None
        a, b = bits[:2]
        half, nab = xor(a, b)
        if len(bits) == 2:
            return half, cell("inv", nab)
        total, nc = xor(half, bits[2])
        return total, cell("nand2", nab, nc)

    # Each row absorbs a shifted partial product and the sum/carry of the
    # previous row. Carries advance one column only, until the final ripple.
    sums, carries = {}, {}
    for j in range(16):
        next_sum, next_carry = {}, {}
        for k in range(j, j + 16):
            pp = cell("inv", cell("nand2", f"a{k-j}", f"b{j}"))
            bits = [pp] + [row[k] for row in (sums, carries) if k in row]
            s, c = add(bits)
            next_sum[k] = s
            if c:
                next_carry[k+1] = c
        # Low column is complete. A NOR with tied inputs is the output buffer's inverter.
        cell("nor2", next_sum[j], next_sum[j], out=f"np{j}")
        cell("inv", f"np{j}", out=f"p{j}")
        sums, carries = next_sum, next_carry
    carry = None
    for k in range(16, 32):
        bits = [row[k] for row in (sums, carries) if k in row]
        if carry:
            bits.append(carry)
        s, carry = add(bits)
        cell("nor2", s, s, out=f"np{k}")
        cell("inv", f"np{k}", out=f"p{k}")
    lines += [".options method=gear itl4=40", f".tran {period * 40}p {len(VECTORS) * period}n"]
    lines += [".save " + " ".join(f"v(p{k})" for k in range(i, i + 8)) for i in range(0, 32, 8)]
    return lines


def ring():
    # Scale this repository's big_ring() measurement fixture to 1001 stages.
    lines = header("1001-stage MOS1 ring, current-pulse startup")
    lines += ["vdd vdd 0 1.8",
              ".model nm nmos(level=1 vto=0.5 kp=100u lambda=0.02 cgso=1n cgdo=1n cj=1e-4 tox=10n)",
              ".model pm pmos(level=1 vto=-0.5 kp=40u lambda=0.02 cgso=1n cgdo=1n cj=1e-4 tox=10n)",
              "ik 0 n0 pulse(0 1m 0 0.1n 0.1n 0.5n 1)"]
    for i in range(1001):
        out = (i + 1) % 1001
        lines += [f"mp{i} n{out} n{i} vdd vdd pm w=2u l=0.5u ad=2p as=2p",
                  f"mn{i} n{out} n{i} 0 0 nm w=1u l=0.5u ad=1p as=1p",
                  f"c{i} n{out} 0 5f"]
    return lines + [".tran 0.1n 3n", ".save v(n0) v(n1) v(n500) v(n1000)"]


def chain():
    lines = header("1000-stage BSIM4 inverter chain", "bsim4") + INV
    lines += ["vdd vdd 0 1.8", "vin n0 0 pulse(0 1.8 50p 25p 25p 300p 1n)"]
    for i in range(1000):
        lines.append(f"x{i} n{i} n{i+1} vdd inv")
    # Initialize a quiescent chain and launch a single pulse.
    lines.append(".ic v(vdd)=1.8")
    for i in range(1, 1000, 2):
        lines.append(f".ic v(n{i})=1.8")
    return lines + [".options method=gear", ".tran 20p 1n uic", ".save v(n0) v(n500) v(n1000)"]


def grid():
    lines = header("300 by 300 resistive power grid with local decoupling")
    lines += ["vdd vdd 0 1.8", "rfeed vdd g0 0.2"]
    for i in range(90000):
        lines.append(f"c{i} g{i} 0 10f")
        if i % 300:
            lines.append(f"rh{i} g{i-1} g{i} 0.5")
        if i >= 300:
            lines.append(f"rv{i} g{i-300} g{i} 0.5")
    for i in (3010, 45150, 89999):
        lines.append(f"i{i} g{i} 0 pulse(0 1m 1p 1p 1p 100p 200p)")
    return lines + [".tran 1p 5p", ".save v(g0) v(g3010) v(g45150) v(g89999)"]


def write(name, lines):
    (HERE / (name + ".cir")).write_text("\n".join([*lines, ".end", ""]), encoding="ascii")


if __name__ == "__main__":
    for model in ("mos1", "bsim4"):
        write("mult16_" + model, multiplier(model))
    write("ring1001_mos1", ring())
    write("inv_chain1000_bsim4", chain())
    write("rc_grid_300", grid())
