#!/usr/bin/env python3
"""Time release spx processes and check settled multiplier outputs.

Provenance: original benchmark harness for the circuits generated by gen.py.
"""
import argparse
import bisect
import hashlib
import os
from pathlib import Path
import re
from statistics import median
import subprocess
import sys
import tempfile
import time

sys.dont_write_bytecode = True
from gen import HERE, VECTOR_NS, VECTORS

DECKS = ("ring1001_mos1", "inv_chain1000_bsim4", "rc_grid_300", "mult16_mos1", "mult16_bsim4")
PHASES = ("setup+parse", "device", "assembly", "symbolic", "numeric", "solve", "control", "output")


def check_product(header, values, period):
    names = [line.split()[1] for line in header.split("Variables:\n")[-1].splitlines()]
    order = [names.index(f"v(p{k})") for k in range(32)]
    tokens = values.split()
    width = len(names) + 1
    times = [float(t) for t in tokens[1::width]]
    for i, (a, b) in enumerate(VECTORS, 1):
        t = i * period * 1e-9
        sample = bisect.bisect_right(times, t + 1e-20) - 1
        if sample < 0 or times[sample] < t - 0.15e-9:
            raise ValueError(f"no sample near {t:g} s")
        for bit, index in enumerate(order):
            v = float(tokens[sample * width + 1 + index])
            high = bool((a * b) & (1 << bit))
            if not (1.44 <= v <= 1.98 if high else -0.18 <= v <= 0.36):
                raise ValueError(f"{a:#06x} * {b:#06x}, bit {bit}, t={times[sample]:g}: "
                                 f"expected {int(high)}, observed {v:g} V")


def sample(binary, deck, jobs, raw, profile):
    env = os.environ.copy()
    env.pop("SPX_PROFILE_DEVICES", None)
    env.pop("SPX_PROFILE_MATRIX", None)
    env.pop("SPX_PROFILE", None)
    if profile:
        env["SPX_PROFILE"] = "1"
    start = time.perf_counter()
    run = subprocess.run([binary, "run", *([] if jobs == "default" else ["-j", jobs]),
                          HERE / (deck + ".cir"), "-r", raw], env=env, capture_output=True, text=True)
    wall = (time.perf_counter() - start) * 1000
    if run.returncode:
        raise RuntimeError(run.stderr)
    header, values = raw.read_text().split("Values:\n")
    if deck.startswith("mult16"):
        check_product(header, values, VECTOR_NS[deck.split("_")[-1]])
    digest = hashlib.sha256((header.split("Variables:\n")[-1] + values).encode()).digest()
    phases = {k: float(v) for k, v in re.findall(r"^spx-phase (\w+) ([\d.]+)$", run.stderr, re.M)}
    if profile:
        phases["setup+parse"] = sum(phases[k] for k in ("read", "netlist_pre", "flatten", "netlist_parse", "setup"))
        factors = re.search(r"^spx-factors (\d+) (\d+)$", run.stderr, re.M)
        points = re.search(r"Transient Analysis: (\d+) points", run.stdout, re.I)
        stats = re.search(r"Transient: (\d+) accepted steps, (\d+) rejected, (\d+) Newton iterations", run.stdout)
        if not factors or not points or not stats:
            raise ValueError(f"incomplete profile: {run.stdout} {run.stderr}")
        identical = re.search(r"^spx-identical (\d+)$", run.stderr, re.M)
        counts = tuple(map(int, (stats[3], points[1], stats[2], *factors.groups(),
                                 identical[1] if identical else 0)))
        workers = re.search(r"^spx-workers (\d+)$", run.stderr, re.M)
        return [wall, *(phases[k] for k in PHASES)], counts, digest, workers[1] if workers else None
    return wall, digest


def check_bits(binary, decks, directory):
    """Compare round-trip JSON for every internal and exported binary64 sample."""
    for deck in decks:
        path = directory / (deck + ".cir")
        path.write_text("".join(line for line in (HERE / path.name).read_text().splitlines(True)
                                if line.strip().lower().split()[:1] != [".save"]))
        digests = []
        for jobs in (["-j1"], []):
            with tempfile.TemporaryFile() as result:
                subprocess.run([binary, "run", *jobs, "--json", path], stdout=result, check=True)
                result.seek(0)
                digest = hashlib.sha256()
                for chunk in iter(lambda: result.read(1 << 20), b""):
                    digest.update(chunk)
                digests.append(digest.hexdigest())
        if digests[0] != digests[1]:
            raise ValueError(f"{deck}: full-precision waveforms differ by worker count")
        print(f"{deck}: identical ({digests[0]})", flush=True)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--binary", type=Path, default=HERE.parents[1] / "target/release/spx")
    p.add_argument("--allow-worker-differences", action="store_true",
                   help="report historical baselines even if workers produced different results")
    p.add_argument("--check-bits", action="store_true",
                   help="compare every full-precision vector at one and default workers instead of timing")
    p.add_argument("--wall-binary", type=Path, help="unchanged HEAD executable for baseline wall times")
    p.add_argument("--runs", type=int, default=3)
    p.add_argument("--deck", choices=DECKS, action="append")
    p.add_argument("--jobs", choices=("1", "default"), action="append")
    args = p.parse_args()
    if args.runs < 1:
        p.error("--runs must be positive")
    if args.check_bits:
        with tempfile.TemporaryDirectory() as tmp:
            check_bits(args.binary.resolve(), args.deck or DECKS, Path(tmp))
        return
    titles = ("Deck", "Workers", "Wall", *PHASES, "Newton", "Points", "Rejected", "Pivot", "Refactor", "Identical")
    print(f"Median timings in milliseconds over {args.runs} run(s).\n")
    print("| " + " | ".join(titles) + " |")
    print("|" + "---|" * len(titles), flush=True)
    with tempfile.TemporaryDirectory() as tmp:
        raw = Path(tmp) / "out.raw"
        for deck in args.deck or DECKS:
            expected = None
            for jobs in args.jobs or ("1", "default"):
                rows = []
                local = None
                for _ in range(args.runs):
                    row, counts, digest, workers = sample(args.binary.resolve(), deck, jobs, raw, True)
                    if args.wall_binary:
                        row[0], reference = sample(args.wall_binary.resolve(), deck, jobs, raw, False)
                        if digest != reference:
                            raise ValueError(f"{deck}: wall and profile builds differ")
                    if expected is None:
                        expected = digest, counts
                    if local is None:
                        local = digest, counts
                    if (digest, counts) != local:
                        raise ValueError(f"{deck}: waveform or work counts changed on repeated runs")
                    if (digest, counts) != expected:
                        message = f"{deck}: waveform or work counts differ by worker count"
                        if not args.allow_worker_differences:
                            raise ValueError(message)
                        print(message, file=sys.stderr)
                    rows.append(row)
                label = f"default ({workers})" if jobs == "default" and workers else jobs
                print("| " + " | ".join([deck, label, *(f"{median(col):.2f}" for col in zip(*rows)),
                                          *map(str, counts)]) + " |", flush=True)


if __name__ == "__main__":
    main()
