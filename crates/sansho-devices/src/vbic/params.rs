//! Nominal VBIC card and parameter domain checks.
//! Provenance: ngspice 44 manual §§7.3.4 and 27.5.2. Defaults and aliases
//! that require black-box confirmation are recorded in docs/vbic.md.

use crate::model::ModelParams;
use sansho_diag::Diagnostic;

/// Nominal parameters shared by all instances of a level-four card.
#[derive(Clone, Debug)]
pub struct Model {
    pub(super) polarity: f64,
    /// Reference temperature in Celsius, when given on the model.
    pub tnom: Option<f64>,
    // Lead and epitaxial resistances, drift and stored carriers.
    pub(super) rcx: f64,
    pub(super) rci: f64,
    pub(super) vo: f64,
    pub(super) gamm: f64,
    pub(super) hrcf: f64,
    pub(super) rbx: f64,
    pub(super) rbi: f64,
    pub(super) re: f64,
    pub(super) rs: f64,
    pub(super) rbp: f64,
    // Forward and reverse transport and normalized base charge.
    pub(super) is_: f64,
    pub(super) nf: f64,
    pub(super) nr: f64,
    pub(super) isrr: f64,
    pub(super) vef: f64,
    pub(super) ver: f64,
    pub(super) ikf: f64,
    pub(super) ikr: f64,
    pub(super) nkf: f64,
    pub(super) qbm: f64,
    // Junction capacitances and smoothing.
    pub(super) fc: f64,
    pub(super) cbeo: f64,
    pub(super) cje: f64,
    pub(super) pe: f64,
    pub(super) me: f64,
    pub(super) aje: f64,
    pub(super) cbco: f64,
    pub(super) cjc: f64,
    pub(super) qco: f64,
    pub(super) cjep: f64,
    pub(super) pc: f64,
    pub(super) mc: f64,
    pub(super) ajc: f64,
    pub(super) cjcp: f64,
    pub(super) ps: f64,
    pub(super) ms: f64,
    pub(super) ajs: f64,
    pub(super) ccso: f64,
    pub(super) vrt: f64,
    pub(super) art: f64,
    // Ideal and recombination branches, breakdown and avalanche.
    pub(super) ibei: f64,
    pub(super) wbe: f64,
    pub(super) nei: f64,
    pub(super) iben: f64,
    pub(super) nen: f64,
    pub(super) ibci: f64,
    pub(super) nci: f64,
    pub(super) ibcn: f64,
    pub(super) ncn: f64,
    pub(super) avc1: f64,
    pub(super) avc2: f64,
    pub(super) vbbe: f64,
    pub(super) nbbe: f64,
    pub(super) ibbe: f64,
    pub(super) ebbe: Option<f64>,
    // Parasitic transistor.
    pub(super) isp: f64,
    pub(super) wsp: f64,
    pub(super) nfp: f64,
    pub(super) ibeip: f64,
    pub(super) ibenp: f64,
    pub(super) ibcip: f64,
    pub(super) ncip: f64,
    pub(super) ibcnp: f64,
    pub(super) ncnp: f64,
    pub(super) ikp: f64,
    // Storage, excess phase, noise and heating.
    pub(super) tf: f64,
    pub(super) qtf: f64,
    pub(super) xtf: f64,
    pub(super) vtf: f64,
    pub(super) itf: f64,
    pub(super) tr: f64,
    pub(super) td: f64,
    pub(super) kfn: f64,
    pub(super) afn: f64,
    pub(super) bfn: f64,
    pub(super) selft: f64,
    pub(super) rth: f64,
    pub(super) cth: f64,
    // Temperature dependence.
    pub(super) xre: f64,
    pub(super) xrbi: f64,
    pub(super) xrbp: f64,
    pub(super) xrbx: f64,
    pub(super) xrci: f64,
    pub(super) xrcx: f64,
    pub(super) xrs: f64,
    pub(super) xvo: f64,
    pub(super) ea: f64,
    pub(super) eaie: f64,
    pub(super) eaic: f64,
    pub(super) eais: f64,
    pub(super) eane: f64,
    pub(super) eanc: f64,
    pub(super) eans: f64,
    pub(super) eap: f64,
    pub(super) xis: f64,
    pub(super) xii: f64,
    pub(super) xin: f64,
    pub(super) tnf: f64,
    pub(super) tavc: f64,
    pub(super) xikf: f64,
    pub(super) xisr: f64,
    pub(super) dear: f64,
    pub(super) tvbbe1: f64,
    pub(super) tvbbe2: f64,
    pub(super) tnbbe: f64,
    pub(super) dtemp: f64,
}

impl Model {
    /// Bind a numeric card, retaining unused keys for the caller's diagnostic.
    pub fn from_params(p: &ModelParams, polarity: f64) -> Result<Self, Diagnostic> {
        // The RCI impedance and reverse-noise measurements resolve finite
        // intrinsic series resistance even when the card specifies zero.
        let resistance = |name, omitted| match p.opt(&[name]) {
            Some(r) if r == 0. || (name == "rci" && r < 0.) => 0.01,
            Some(r) => r,
            None => omitted,
        };
        let xrb = p.get("xrb", 0.);
        let xrc = p.get("xrc", 0.);
        p.accept(&["level", "vers", "vref"]);
        let m = Self {
            polarity,
            tnom: p.opt(&["tnom", "tref"]),
            rcx: p.get("rcx", 0.),
            rci: resistance("rci", 0.1),
            vo: p.get("vo", 0.),
            gamm: p.get("gamm", 0.),
            hrcf: p.get("hrcf", 0.),
            rbx: resistance("rbx", 0.),
            rbi: resistance("rbi", 0.1),
            re: p.get("re", 0.),
            rs: p.get("rs", 0.),
            rbp: resistance("rbp", 0.1),
            is_: p.get("is", 1e-16),
            nf: p.get("nf", 1.),
            nr: p.get("nr", 1.),
            isrr: p.get("isrr", 1.),
            vef: p.get("vef", 0.),
            ver: p.get("ver", 0.),
            ikf: p.get("ikf", 0.),
            ikr: p.get("ikr", 0.),
            nkf: p.get("nkf", 0.5),
            qbm: p.get("qbm", 0.),
            fc: p.get("fc", 0.9),
            cbeo: p.get("cbeo", 0.),
            cje: p.get("cje", 0.),
            pe: p.get("pe", 0.75),
            me: p.get("me", 0.33),
            aje: p.get("aje", -0.5),
            cbco: p.get("cbco", 0.),
            cjc: p.get("cjc", 0.),
            qco: p.get("qco", 0.),
            cjep: p.get("cjep", 0.),
            pc: p.get("pc", 0.75),
            mc: p.get("mc", 0.33),
            ajc: p.get("ajc", -0.5),
            cjcp: p.get("cjcp", 0.),
            ps: p.get("ps", 0.75),
            ms: p.get("ms", 0.33),
            ajs: p.get("ajs", -0.5),
            ccso: p.get("ccso", 0.),
            vrt: p.get("vrt", 0.),
            art: p.get("art", 0.1),
            ibei: p.get("ibei", 1e-18),
            wbe: p.get("wbe", 1.),
            nei: p.get("nei", 1.),
            iben: p.get("iben", 0.),
            nen: p.get("nen", 2.),
            ibci: p.get("ibci", 1e-16),
            nci: p.get("nci", 1.),
            ibcn: p.get("ibcn", 0.),
            ncn: p.get("ncn", 2.),
            avc1: p.get("avc1", 0.),
            avc2: p.get("avc2", 0.),
            vbbe: p.get("vbbe", 0.),
            nbbe: p.get("nbbe", 1.),
            ibbe: p.get("ibbe", 1e-6),
            ebbe: p.opt(&["ebbe"]),
            isp: p.get("isp", 0.),
            wsp: p.get("wsp", 1.),
            nfp: p.get("nfp", 1.),
            ibeip: p.get("ibeip", 0.),
            ibenp: p.get("ibenp", 0.),
            ibcip: p.get("ibcip", 0.),
            ncip: p.get("ncip", 1.),
            ibcnp: p.get("ibcnp", 0.),
            ncnp: p.get("ncnp", 2.),
            ikp: p.get("ikp", 0.),
            tf: p.get("tf", 0.),
            qtf: p.get("qtf", 0.),
            xtf: p.get("xtf", 0.),
            vtf: p.get("vtf", 0.),
            itf: p.get("itf", 0.),
            tr: p.get("tr", 0.),
            td: p.get("td", 0.),
            kfn: p.get("kfn", 0.),
            afn: p.get("afn", 1.),
            bfn: p.get("bfn", 1.),
            selft: p.get("selft", 0.),
            rth: p.get("rth", 0.),
            cth: p.get("cth", 0.),
            xre: p.get("xre", 0.),
            xrbi: p.get("xrbi", 0.),
            xrbp: p.get("xrbp", 0.),
            xrbx: p.get("xrbx", xrb),
            xrci: p.get("xrci", 0.),
            xrcx: p.get("xrcx", xrc),
            xrs: p.get("xrs", 0.),
            xvo: p.get("xvo", 0.),
            ea: p.get("ea", 1.12),
            eaie: p.get("eaie", 1.12),
            eaic: p.get("eaic", 1.12),
            eais: p.get("eais", 1.12),
            eane: p.get("eane", 1.12),
            eanc: p.get("eanc", 1.12),
            eans: p.get("eans", 1.12),
            eap: p.get("eap", 1.12),
            xis: p.get("xis", 3.),
            xii: p.get("xii", 3.),
            xin: p.get("xin", 3.),
            tnf: p.get("tnf", 0.),
            tavc: p.get("tavc", 0.),
            xikf: p.get("xikf", 0.),
            xisr: p.get("xisr", 0.),
            dear: p.get("dear", 0.),
            tvbbe1: p.get("tvbbe1", 0.),
            tvbbe2: p.get("tvbbe2", 0.),
            tnbbe: p.get("tnbbe", 0.),
            dtemp: p.get("dtemp", 0.),
        };
        if !(0. ..1.).contains(&m.fc)
            || ![m.wbe, m.wsp].iter().all(|v| (0. ..=1.).contains(v))
            || !matches!(m.selft, 0. | 1.)
            || [
                m.nf, m.nr, m.nei, m.nen, m.nci, m.ncn, m.nfp, m.ncip, m.ncnp, m.nbbe, m.pe, m.pc,
                m.ps, m.nkf,
            ]
            .iter()
            .any(|v| *v <= 0.)
            || [
                m.rcx, m.rci, m.rbx, m.rbi, m.rbp, m.re, m.rs, m.vo, m.hrcf, m.gamm, m.is_, m.isrr,
                m.ikf, m.ikr, m.ikp, m.td, m.rth, m.cth, m.kfn, m.ibei, m.iben, m.ibci, m.ibcn,
                m.isp, m.ibeip, m.ibenp, m.ibcip, m.ibcnp, m.cje, m.cjc, m.cjep, m.cjcp, m.tf,
                m.tr,
            ]
            .iter()
            .any(|v| *v < 0.)
        {
            return Err(Diagnostic::error(
                "E-ELAB-PARAM",
                "invalid VBIC resistance, current, charge, emission coefficient or model selector",
            ));
        }
        Ok(m)
    }
}
